//! Окно «О Todo режиме» — `AboutTodoWindowController` оригинала
//! (docs/ui-spec.md §11): как включить Todo-режим. Его показывает кнопка «ⓘ»
//! рядом с флажком «Показывать Todo режим в меню» на вкладке «Основные» —
//! больше нигде, как и в оригинале.
//!
//! Само окно построено в модуле окна настроек (`ui::prefs::about_todo`); ⌘W и
//! ⌘M в нём, как и в окне настроек, обрабатывает главное меню (`menu::main_menu`)
//! в любой раскладке. Здесь — вход для остального приложения.

use objc2::MainThreadMarker;

/// Показать окно (создать при первом вызове) и вывести приложение вперёд —
/// `showTodoModeHelp` оригинала.
pub fn show() {
    if let Some(mtm) = MainThreadMarker::new() {
        super::prefs::about_todo::show(mtm);
    }
}
